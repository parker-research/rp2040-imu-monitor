/*
 * RP2040 IMU Monitor Firmware
 * Target: RP2040-Zero + LSM303-family accelerometer/magnetometer.
 *
 * Responsibilities:
 *   - Auto-detect and configure an LSM303 (DLH/DLM/DLHC/D/AGR) on I2C1 (SDA=GP26, SCL=GP27).
 *   - Report all readings as JSONL over USB-CDC serial, ~4 Hz by default (configurable).
 *   - Show health on the RP2040-Zero's WS2812 RGB LED (GP16).
 *   - Survive faults: watchdog, bounded I2C timeouts, I2C bus recovery, automatic sensor
 *     re-detection, periodic config read-back (catches sensor brown-out resets), and
 *     stuck-data detection.
 *
 * Every line printed is a single JSON object with a "type" field:
 *   boot, sample, event, help, error.
 * See README.md for the field reference and serial commands.
 */

