// ---------------------------------------------------------------------------
// Pin map
// ---------------------------------------------------------------------------
#define PIN_I2C_SDA   26
#define PIN_I2C_SCL   27
#define I2C_PORT      i2c1     // GP26/GP27 are I2C1 SDA/SCL.
#define PIN_RGB_LED   16       // On-board WS2812 on the RP2040-Zero.
#define ADC_TEMP_CHANNEL 4     // RP2040 internal temperature sensor.

// ---------------------------------------------------------------------------
// Tunables
// ---------------------------------------------------------------------------
#ifndef DEFAULT_REPORT_INTERVAL_MS
#define DEFAULT_REPORT_INTERVAL_MS 250
#endif

static const uint32_t I2C_BAUD_HZ = 100 * 1000;   // Conservative; bodge wires.

static const uint32_t MIN_REPORT_INTERVAL_MS = 50;
static const uint32_t MAX_REPORT_INTERVAL_MS = 60 * 1000;

// [WATCHDOG] Main loop must feed the dog within this time. Each I2C transaction is capped at
// 5 ms and each USB-CDC write at ~500 ms (SDK default), so this has generous headroom.
static const uint32_t WATCHDOG_TIMEOUT_MS = 2000;

// After this many consecutive failed sensor reads, declare the sensor lost and re-detect.
static const uint32_t READ_FAIL_LIMIT = 3;
// How often to retry detection while no sensor is present.
static const uint32_t REDETECT_INTERVAL_MS = 1000;
// How often to read back the sensor configuration registers.
static const uint32_t CONFIG_VERIFY_INTERVAL_MS = 5000;
// Report health as degraded for this long after any I2C error.
static const uint32_t ERROR_DEGRADED_HOLD_MS = 5000;
// Readings bit-for-bit identical for this long => sensor considered stuck.
static const uint32_t STALE_DATA_MS = 2000;
// Accel magnitude outside this window is physically implausible for a stationary-ish mount.
static const float ACCEL_PLAUSIBLE_MIN_G = 0.3f;
static const float ACCEL_PLAUSIBLE_MAX_G = 2.0f;

// ---------------------------------------------------------------------------
// Watchdog breadcrumbs
//
// watchdog scratch[0..3] survive a watchdog reset (the SDK uses scratch[4..7]). We record
// which stage of the loop we're in so that after a watchdog reset we can report where it hung.
// ---------------------------------------------------------------------------
#define SCRATCH_MAGIC          0x1A0303u
#define SCRATCH_IDX_STAGE      0
#define SCRATCH_IDX_WDT_COUNT  1

typedef enum {
    STAGE_BOOT = 1,
    STAGE_SERIAL_IN,
    STAGE_SENSOR_DETECT,
    STAGE_SENSOR_READ,
    STAGE_SENSOR_VERIFY,
    STAGE_REPORT,
    STAGE_IDLE,
} stage_t;

static void breadcrumb(stage_t stage) {
    watchdog_hw->scratch[SCRATCH_IDX_STAGE] = (SCRATCH_MAGIC << 8) | (uint32_t)stage;
}

static const char *stage_name(uint32_t scratch) {
    if ((scratch >> 8) != SCRATCH_MAGIC) return "unknown";
    switch ((stage_t)(scratch & 0xFFu)) {
        case STAGE_BOOT:          return "boot";
        case STAGE_SERIAL_IN:     return "serial_in";
        case STAGE_SENSOR_DETECT: return "sensor_detect";
        case STAGE_SENSOR_READ:   return "sensor_read";
        case STAGE_SENSOR_VERIFY: return "sensor_verify";
        case STAGE_REPORT:        return "report";
        case STAGE_IDLE:          return "idle";
    }
    return "unknown";
}

// ---------------------------------------------------------------------------
// State
// ---------------------------------------------------------------------------
typedef struct {
    // Boot info.
    bool        wdt_reboot;          // Last reset was a watchdog *timeout* (not a requested reboot).
    const char *wdt_last_stage;      // Breadcrumb at time of watchdog reset.
    uint32_t    wdt_reboot_count;    // Watchdog timeouts since power-on.
    bool        wdt_led_flag;        // Show the magenta LED marker (cleared by `clearwdt`).

    // Sensor.
    lsm303_t        imu;
    bool            imu_ok;
    lsm303_sample_t last;
    bool            last_valid;

    // Health counters.
    uint32_t i2c_err_total;
    uint32_t read_fail_streak;
    uint32_t reinit_count;
    uint32_t config_restore_count;
    uint32_t last_error_ms;          // 0 = never.
    uint32_t data_unchanged_since_ms;
    bool     stale;
    bool     plausible;

    // Reporting.
    uint32_t report_interval_ms;
    uint32_t seq;
} app_t;

static app_t g;

// ---------------------------------------------------------------------------
// JSON output helpers
// ---------------------------------------------------------------------------
typedef struct {
    char   buf[640];
    size_t len;
    bool   overflow;
} jbuf_t;

static void jb_init(jbuf_t *jb) {
    jb->len = 0;
    jb->overflow = false;
    jb->buf[0] = '\0';
}

static void jb_printf(jbuf_t *jb, const char *fmt, ...) {
    if (jb->overflow) return;
    va_list ap;
    va_start(ap, fmt);
    const int n = vsnprintf(jb->buf + jb->len, sizeof(jb->buf) - jb->len, fmt, ap);
    va_end(ap);
    if (n < 0 || (size_t)n >= sizeof(jb->buf) - jb->len) {
        jb->overflow = true;
        return;
    }
    jb->len += (size_t)n;
}

/// Append `,"key":<float>` or `,"key":null` if not finite.
static void jb_float(jbuf_t *jb, const char *key, float v, int decimals) {
    if (isfinite(v)) jb_printf(jb, ",\"%s\":%.*f", key, decimals, (double)v);
    else jb_printf(jb, ",\"%s\":null", key);
}

static void jb_vec3f(jbuf_t *jb, const char *key, const float v[3], int decimals) {
    jb_printf(jb, ",\"%s\":[%.*f,%.*f,%.*f]", key,
              decimals, (double)v[0], decimals, (double)v[1], decimals, (double)v[2]);
}

static void jb_vec3i(jbuf_t *jb, const char *key, const int16_t v[3]) {
    jb_printf(jb, ",\"%s\":[%d,%d,%d]", key, v[0], v[1], v[2]);
}

static void jb_emit(jbuf_t *jb) {
    // Feed the dog before each (potentially blocking) USB write.
    watchdog_update();
    if (jb->overflow) {
        // Never emit a truncated (invalid) JSON line.
        printf("{\"type\":\"error\",\"msg\":\"json_overflow\"}\n");
        return;
    }
    printf("%s}\n", jb->buf);
}

static uint32_t now_ms(void) {
    return to_ms_since_boot(get_absolute_time());
}

/// Start a JSON object with the common header fields.
static void jb_begin(jbuf_t *jb, const char *type) {
    jb_init(jb);
    jb_printf(jb, "{\"type\":\"%s\",\"t_ms\":%lu", type, (unsigned long)now_ms());
}

/// Emit `{"type":"event","event":"<name>"}` with optional extra pre-formatted JSON fields.
static void emit_event(const char *name, const char *extra_fmt, ...) {
    jbuf_t jb;
    jb_begin(&jb, "event");
    jb_printf(&jb, ",\"event\":\"%s\"", name);
    if (extra_fmt != NULL) {
        char extra[160];
        va_list ap;
        va_start(ap, extra_fmt);
        vsnprintf(extra, sizeof(extra), extra_fmt, ap);
        va_end(ap);
        jb_printf(&jb, ",%s", extra);
    }
    jb_emit(&jb);
}

static void emit_error(const char *msg) {
    jbuf_t jb;
    jb_begin(&jb, "error");
    jb_printf(&jb, ",\"msg\":\"%s\"", msg);
    jb_emit(&jb);
}

// ---------------------------------------------------------------------------
// MCU temperature
// ---------------------------------------------------------------------------
static float read_mcu_temp_c(void) {
    adc_select_input(ADC_TEMP_CHANNEL);
    uint32_t sum = 0;
    for (int i = 0; i < 8; i++) sum += adc_read();
    const float volts = ((float)sum / 8.0f) * 3.3f / 4096.0f;
    // RP2040 datasheet section 4.9.5.
    return 27.0f - (volts - 0.706f) / 0.001721f;
}

// ---------------------------------------------------------------------------
// I2C bus setup + recovery
// ---------------------------------------------------------------------------
static void i2c_setup(void) {
    i2c_init(I2C_PORT, I2C_BAUD_HZ);
    gpio_set_function(PIN_I2C_SDA, GPIO_FUNC_I2C);
    gpio_set_function(PIN_I2C_SCL, GPIO_FUNC_I2C);
    // Breakouts usually have their own pull-ups; the internal ones (~50k) are a backup.
    gpio_pull_up(PIN_I2C_SDA);
    gpio_pull_up(PIN_I2C_SCL);
}

/// Free a slave that's holding SDA low mid-transfer (e.g. after a reset in the middle of a
/// read): bit-bang up to 9 SCL pulses until SDA releases, then issue a STOP.
static void i2c_bus_recover(void) {
    i2c_deinit(I2C_PORT);

    // Open-drain emulation: "high" = input with pull-up, "low" = drive low.
    gpio_init(PIN_I2C_SDA);
    gpio_init(PIN_I2C_SCL);
    gpio_pull_up(PIN_I2C_SDA);
    gpio_pull_up(PIN_I2C_SCL);
    gpio_set_dir(PIN_I2C_SDA, GPIO_IN);
    gpio_set_dir(PIN_I2C_SCL, GPIO_IN);
    gpio_put(PIN_I2C_SDA, 0);
    gpio_put(PIN_I2C_SCL, 0);
    sleep_us(10);

    for (int i = 0; i < 9 && !gpio_get(PIN_I2C_SDA); i++) {
        gpio_set_dir(PIN_I2C_SCL, GPIO_OUT);  // SCL low
        sleep_us(10);
        gpio_set_dir(PIN_I2C_SCL, GPIO_IN);   // SCL high
        sleep_us(10);
    }

    // STOP: SDA low -> high while SCL high.
    gpio_set_dir(PIN_I2C_SDA, GPIO_OUT);
    sleep_us(10);
    gpio_set_dir(PIN_I2C_SCL, GPIO_IN);
    sleep_us(10);
    gpio_set_dir(PIN_I2C_SDA, GPIO_IN);
    sleep_us(10);

    i2c_setup();
}

// ---------------------------------------------------------------------------
// Sensor management
// ---------------------------------------------------------------------------
static void note_i2c_error(uint32_t now) {
    g.i2c_err_total++;
    g.last_error_ms = now ? now : 1;
}

static bool sensor_try_init(void) {
    breadcrumb(STAGE_SENSOR_DETECT);
    if (!lsm303_detect(&g.imu, I2C_PORT)) return false;
    if (!lsm303_configure(&g.imu)) {
        emit_event("sensor_config_failed", "\"sensor\":\"%s\"", lsm303_variant_name(g.imu.variant));
        return false;
    }
    g.imu_ok = true;
    g.read_fail_streak = 0;
    g.last_valid = false;
    g.stale = false;
    emit_event("sensor_detected", "\"sensor\":\"%s\",\"acc_addr\":%u,\"mag_addr\":%u",
               lsm303_variant_name(g.imu.variant), g.imu.acc_addr, g.imu.mag_addr);
    return true;
}

static void sensor_mark_lost(const char *why) {
    emit_event("sensor_lost", "\"sensor\":\"%s\",\"reason\":\"%s\"",
               lsm303_variant_name(g.imu.variant), why);
    g.imu_ok = false;
    g.last_valid = false;
    g.imu.variant = LSM303_NONE;
}

/// Read the sensor, updating health state. Returns true if `g.last` holds a fresh sample.
static bool sensor_poll(uint32_t now) {
    if (!g.imu_ok) return false;

    breadcrumb(STAGE_SENSOR_READ);
    lsm303_sample_t s;
    if (!lsm303_read(&g.imu, &s)) {
        note_i2c_error(now);
        g.read_fail_streak++;
        if (g.read_fail_streak >= READ_FAIL_LIMIT) {
            sensor_mark_lost("read_failures");
            i2c_bus_recover();
        }
        return false;
    }
    g.read_fail_streak = 0;

    // Stuck-data detection: real sensors always have some LSB noise.
    const bool unchanged = g.last_valid &&
        memcmp(s.acc_raw, g.last.acc_raw, sizeof(s.acc_raw)) == 0 &&
        memcmp(s.mag_raw, g.last.mag_raw, sizeof(s.mag_raw)) == 0;
    if (!unchanged) g.data_unchanged_since_ms = now;
    g.stale = unchanged && (now - g.data_unchanged_since_ms) >= STALE_DATA_MS;

    const float amag = sqrtf(s.acc_g[0] * s.acc_g[0] + s.acc_g[1] * s.acc_g[1] + s.acc_g[2] * s.acc_g[2]);
    g.plausible = amag >= ACCEL_PLAUSIBLE_MIN_G && amag <= ACCEL_PLAUSIBLE_MAX_G;

    g.last = s;
    g.last_valid = true;
    return true;
}

/// Periodically confirm the chip still holds our configuration. LSM303s reset to power-down
/// on a supply glitch, after which reads still succeed but return frozen data.
static void sensor_verify(uint32_t now) {
    if (!g.imu_ok) return;
    breadcrumb(STAGE_SENSOR_VERIFY);
    bool io_ok;
    if (lsm303_verify_config(&g.imu, &io_ok)) return;
    if (!io_ok) {
        note_i2c_error(now);
        return;  // Read failures are handled by the read path's streak counter.
    }
    note_i2c_error(now);
    g.config_restore_count++;
    const bool ok = lsm303_configure(&g.imu);
    emit_event("sensor_config_restored", "\"ok\":%s", ok ? "true" : "false");
}

static health_t compute_health(uint32_t now) {
    if (!g.imu_ok) return HEALTH_NO_SENSOR;
    const bool recent_error = g.last_error_ms != 0 && (now - g.last_error_ms) < ERROR_DEGRADED_HOLD_MS;
    if (recent_error || g.stale || (g.last_valid && !g.plausible)) return HEALTH_DEGRADED;
    return HEALTH_OK;
}

// ---------------------------------------------------------------------------
// Derived orientation
// ---------------------------------------------------------------------------
static void cross(const float a[3], const float b[3], float out[3]) {
    out[0] = a[1] * b[2] - a[2] * b[1];
    out[1] = a[2] * b[0] - a[0] * b[2];
    out[2] = a[0] * b[1] - a[1] * b[0];
}

static void normalize(float v[3]) {
    const float n = sqrtf(v[0] * v[0] + v[1] * v[1] + v[2] * v[2]);
    if (n > 0.0f) {
        v[0] /= n;
        v[1] /= n;
        v[2] /= n;
    }
}

/// Tilt-compensated heading of the board's +X axis, degrees [0, 360). Uncalibrated (no
/// hard/soft-iron correction), so absolute accuracy depends on the mounting environment.
static float compute_heading_deg(const float acc[3], const float mag[3]) {
    float e[3], n[3];
    cross(mag, acc, e);
    normalize(e);
    cross(acc, e, n);
    normalize(n);
    // Dot with the +X reference vector reduces to the X component.
    float h = atan2f(e[0], n[0]) * (180.0f / (float)M_PI);
    if (h < 0.0f) h += 360.0f;
    return h;
}

// ---------------------------------------------------------------------------
// Reports
// ---------------------------------------------------------------------------
static void emit_sample(uint32_t now, bool fresh) {
    breadcrumb(STAGE_REPORT);
    const health_t health = compute_health(now);

    jbuf_t jb;
    jb_begin(&jb, "sample");
    jb_printf(&jb, ",\"seq\":%lu", (unsigned long)g.seq++);
    jb_printf(&jb, ",\"health\":\"%s\"", health_name(health));
    if (g.imu_ok) jb_printf(&jb, ",\"sensor\":\"%s\"", lsm303_variant_name(g.imu.variant));
    else jb_printf(&jb, ",\"sensor\":null");
    jb_printf(&jb, ",\"fresh\":%s", fresh ? "true" : "false");

    if (g.imu_ok && g.last_valid) {
        const lsm303_sample_t *s = &g.last;
        const float mag_ut[3] = { s->mag_gauss[0] * 100.0f, s->mag_gauss[1] * 100.0f, s->mag_gauss[2] * 100.0f };
        const float ax = s->acc_g[0], ay = s->acc_g[1], az = s->acc_g[2];

        jb_vec3i(&jb, "acc_raw", s->acc_raw);
        jb_vec3f(&jb, "acc_g", s->acc_g, 4);
        jb_float(&jb, "acc_mag_g", sqrtf(ax * ax + ay * ay + az * az), 4);
        jb_vec3i(&jb, "mag_raw", s->mag_raw);
        jb_vec3f(&jb, "mag_uT", mag_ut, 2);
        jb_float(&jb, "mag_mag_uT", sqrtf(mag_ut[0] * mag_ut[0] + mag_ut[1] * mag_ut[1] + mag_ut[2] * mag_ut[2]), 2);
        jb_float(&jb, "roll_deg", atan2f(ay, az) * (180.0f / (float)M_PI), 2);
        jb_float(&jb, "pitch_deg", atan2f(-ax, sqrtf(ay * ay + az * az)) * (180.0f / (float)M_PI), 2);
        jb_float(&jb, "heading_deg", compute_heading_deg(s->acc_g, s->mag_gauss), 2);
        if (s->has_temp) {
            jb_float(&jb, "imu_temp_c", s->temp_c, 2);
            jb_printf(&jb, ",\"imu_temp_raw\":%d", s->temp_raw);
        } else {
            jb_printf(&jb, ",\"imu_temp_c\":null,\"imu_temp_raw\":null");
        }
    } else {
        jb_printf(&jb, ",\"acc_raw\":null,\"acc_g\":null,\"acc_mag_g\":null"
                       ",\"mag_raw\":null,\"mag_uT\":null,\"mag_mag_uT\":null"
                       ",\"roll_deg\":null,\"pitch_deg\":null,\"heading_deg\":null"
                       ",\"imu_temp_c\":null,\"imu_temp_raw\":null");
    }

    jb_float(&jb, "mcu_temp_c", read_mcu_temp_c(), 2);
    jb_printf(&jb, ",\"stale\":%s,\"plausible\":%s",
              g.stale ? "true" : "false", (g.last_valid && g.plausible) ? "true" : "false");
    jb_printf(&jb, ",\"i2c_err\":%lu,\"fail_streak\":%lu,\"reinit\":%lu,\"cfg_restore\":%lu",
              (unsigned long)g.i2c_err_total, (unsigned long)g.read_fail_streak,
              (unsigned long)g.reinit_count, (unsigned long)g.config_restore_count);
    jb_printf(&jb, ",\"wdt_reboot\":%s,\"interval_ms\":%lu",
              g.wdt_reboot ? "true" : "false", (unsigned long)g.report_interval_ms);
    jb_emit(&jb);
}

static void emit_boot_info(void) {
    jbuf_t jb;
    jb_begin(&jb, "boot");
    jb_printf(&jb, ",\"fw\":\"rp2040-imu-monitor\",\"build\":\"" BUILD_TIMESTAMP "\",\"git\":\"" GIT_COMMIT "\"");
    jb_printf(&jb, ",\"wdt_reboot\":%s,\"wdt_last_stage\":", g.wdt_reboot ? "true" : "false");
    if (g.wdt_reboot) jb_printf(&jb, "\"%s\"", g.wdt_last_stage);
    else jb_printf(&jb, "null");
    jb_printf(&jb, ",\"wdt_reboot_count\":%lu,\"wdt_timeout_ms\":%lu",
              (unsigned long)g.wdt_reboot_count, (unsigned long)WATCHDOG_TIMEOUT_MS);
    jb_printf(&jb, ",\"sensor\":\"%s\",\"interval_ms\":%lu",
              lsm303_variant_name(g.imu.variant), (unsigned long)g.report_interval_ms);
    jb_emit(&jb);
}

static void emit_help(void) {
    static const char *const lines[][2] = {
        { "help",            "show this help" },
        { "info",            "print the boot/info record" },
        { "interval <ms>",   "set report interval (50-60000 ms)" },
        { "reinit",          "recover the I2C bus and re-detect the sensor" },
        { "clearwdt",        "clear the watchdog-reboot LED marker" },
        { "reboot",          "reboot the MCU" },
        { "bootsel",         "reboot into the UF2 bootloader" },
    };
    for (size_t i = 0; i < sizeof(lines) / sizeof(lines[0]); i++) {
        jbuf_t jb;
        jb_begin(&jb, "help");
        jb_printf(&jb, ",\"cmd\":\"%s\",\"desc\":\"%s\"", lines[i][0], lines[i][1]);
        jb_emit(&jb);
    }
}

// ---------------------------------------------------------------------------
// Serial command input (newline-terminated lines)
// ---------------------------------------------------------------------------
static void set_interval(uint32_t ms) {
    if (ms < MIN_REPORT_INTERVAL_MS || ms > MAX_REPORT_INTERVAL_MS) {
        emit_error("interval_out_of_range");
        return;
    }
    g.report_interval_ms = ms;
    emit_event("interval_changed", "\"interval_ms\":%lu", (unsigned long)ms);
}

static void handle_command(char *line) {
    // Trim leading/trailing whitespace.
    while (*line == ' ' || *line == '\t') line++;
    size_t n = strlen(line);
    while (n > 0 && (line[n - 1] == ' ' || line[n - 1] == '\t')) line[--n] = '\0';
    if (n == 0) return;

    char *arg = strchr(line, ' ');
    if (arg != NULL) {
        *arg++ = '\0';
        while (*arg == ' ') arg++;
    }

    if (strcmp(line, "help") == 0 || strcmp(line, "?") == 0) {
        emit_help();
    } else if (strcmp(line, "info") == 0) {
        emit_boot_info();
    } else if (strcmp(line, "interval") == 0 && arg != NULL) {
        char *end;
        const unsigned long v = strtoul(arg, &end, 10);
        if (end == arg || *end != '\0') emit_error("bad_number");
        else set_interval((uint32_t)v);
    } else if (strcmp(line, "reinit") == 0) {
        if (g.imu_ok) sensor_mark_lost("user_reinit");
        i2c_bus_recover();
        g.reinit_count++;
        if (!sensor_try_init()) emit_event("sensor_not_found", NULL);
    } else if (strcmp(line, "clearwdt") == 0) {
        g.wdt_led_flag = false;
        emit_event("wdt_flag_cleared", NULL);
    } else if (strcmp(line, "reboot") == 0) {
        emit_event("rebooting", NULL);
        stdio_flush();
        sleep_ms(100);
        watchdog_reboot(0, 0, 0);
        while (true) tight_loop_contents();
    } else if (strcmp(line, "bootsel") == 0) {
        emit_event("rebooting_to_bootsel", NULL);
        stdio_flush();
        sleep_ms(100);
        reset_usb_boot(0, 0);
    } else {
        emit_error("unknown_command");
    }
}

static void poll_serial_input(void) {
    static char buf[64];
    static size_t len = 0;
    static bool discarding = false;

    breadcrumb(STAGE_SERIAL_IN);
    // Bounded: drain at most a handful of chars per loop iteration.
    for (int i = 0; i < 32; i++) {
        const int c = getchar_timeout_us(0);
        if (c == PICO_ERROR_TIMEOUT || c < 0) return;

        if (c == '\r' || c == '\n') {
            if (!discarding) {
                buf[len] = '\0';
                handle_command(buf);
            } else {
                emit_error("line_too_long");
            }
            len = 0;
            discarding = false;
        } else if (!discarding) {
            if (len < sizeof(buf) - 1) buf[len++] = (char)c;
            else discarding = true;
        }
    }
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------
int main(void) {
    // [WATCHDOG] Capture the reset cause before anything else touches the scratch registers.
    // watchdog_enable_caused_reboot() is only true for a real timeout, not for watchdog_reboot().
    g.wdt_reboot = watchdog_enable_caused_reboot();
    const uint32_t prev_stage = watchdog_hw->scratch[SCRATCH_IDX_STAGE];
    const uint32_t prev_count = watchdog_hw->scratch[SCRATCH_IDX_WDT_COUNT];
    g.wdt_last_stage = stage_name(prev_stage);
    if (g.wdt_reboot && (prev_count >> 16) == (SCRATCH_MAGIC & 0xFFFFu)) {
        g.wdt_reboot_count = (prev_count & 0xFFFFu) + 1u;
    } else {
        g.wdt_reboot_count = g.wdt_reboot ? 1u : 0u;
    }
    watchdog_hw->scratch[SCRATCH_IDX_WDT_COUNT] = ((SCRATCH_MAGIC & 0xFFFFu) << 16) | (g.wdt_reboot_count & 0xFFFFu);
    g.wdt_led_flag = g.wdt_reboot;
    breadcrumb(STAGE_BOOT);

    g.report_interval_ms = DEFAULT_REPORT_INTERVAL_MS;
    if (g.report_interval_ms < MIN_REPORT_INTERVAL_MS) g.report_interval_ms = MIN_REPORT_INTERVAL_MS;

    stdio_init_all();
    status_led_init(PIN_RGB_LED);
    status_led_update(HEALTH_BOOT, false, 0);

    adc_init();
    adc_set_temp_sensor_enabled(true);

    // [WATCHDOG] Enable. pause_on_debug=true freezes the counter while a debugger is halted.
    watchdog_enable(WATCHDOG_TIMEOUT_MS, true);

    i2c_bus_recover();  // Also performs i2c_setup(). Clears a bus left wedged by a prior reset.
    sensor_try_init();

    bool     last_cdc_connected = false;
    uint32_t last_cdc_check_ms = 0;
    uint32_t last_redetect_ms = now_ms();
    uint32_t last_verify_ms = now_ms();
    uint32_t next_report_ms = now_ms();

    while (true) {
        watchdog_update();  // [WATCHDOG] Feed dog.
        const uint32_t now = now_ms();

        poll_serial_input();

        // On new USB-CDC connection, (re)print the boot record so the host always sees it.
        if (now - last_cdc_check_ms >= 250) {
            const bool cdc_connected = stdio_usb_connected();
            if (cdc_connected && !last_cdc_connected) {
                sleep_ms(100);  // Let the CDC link settle.
                emit_boot_info();
                emit_help();
            }
            last_cdc_connected = cdc_connected;
            last_cdc_check_ms = now;
        }

        // Sensor absent: periodically recover the bus and retry detection.
        if (!g.imu_ok && (now - last_redetect_ms) >= REDETECT_INTERVAL_MS) {
            last_redetect_ms = now;
            i2c_bus_recover();
            g.reinit_count++;
            sensor_try_init();
        }

        if (g.imu_ok && (now - last_verify_ms) >= CONFIG_VERIFY_INTERVAL_MS) {
            last_verify_ms = now;
            sensor_verify(now);
        }

        if ((int32_t)(now - next_report_ms) >= 0) {
            const bool fresh = sensor_poll(now);
            emit_sample(now, fresh);
            next_report_ms += g.report_interval_ms;
            // If we fell far behind (e.g. USB stalled), resync instead of bursting.
            if ((int32_t)(now - next_report_ms) >= 0) next_report_ms = now + g.report_interval_ms;
        }

        breadcrumb(STAGE_IDLE);
        status_led_update(compute_health(now), g.wdt_led_flag, now);
        sleep_ms(1);
    }
}
